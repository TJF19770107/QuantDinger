# ============================================================
# 数据模型
# ============================================================

class PipelineStatus(Enum):
    PENDING = "pending"
    RUNNING = "running"
    PASSED = "passed"
    FAILED = "failed"
    FIXED = "fixed"        # 自动修复成功
    ABORTED = "aborted"

@dataclass
class StageResult:
    stage: str
    status: PipelineStatus
    duration: float
    output: str
    errors: List[str] = field(default_factory=list)
    coverage: Optional[float] = None

@dataclass
class PipelineConfig:
    spec_dir: str = "./specs"
    output_dir: str = "./src"
    test_dir: str = "./tests"
    max_retries: int = 3
    coverage_threshold: float = 80.0
    complexity_max: str = "B"
    lint_rules: List[str] = field(default_factory=lambda: ["ruff", "mypy", "bandit"])

# ============================================================
# CI流水线引擎
# ============================================================

class CIPipeline:
    """五阶段CI验证流水线"""
    
    def __init__(self, config: PipelineConfig):
        self.config = config
        self.results: List[StageResult] = []
        self.start_time = time.time()
    
    def run(self) -> Dict:
        """执行完整CI流水线"""
        stages = [
            ("Stage1_SpecCheck", self._stage_spec_check),
            ("Stage2_CodeGeneration", self._stage_code_generation),
            ("Stage3_Test", self._stage_test),
            ("Stage4_QualityGate", self._stage_quality_gate),
            ("Stage5_Release", self._stage_release)
        ]
        
        for stage_name, stage_func in stages:
            result = stage_func()
            self.results.append(result)
            if result.status == PipelineStatus.FAILED and stage_name in ("Stage1_SpecCheck",):
                # 前两阶段失败则终止
                break
        
        return self._summary()
    
    def _stage_spec_check(self) -> StageResult:
        """Stage 1: Spec校验"""
        start = time.time()
        spec_dir = Path(self.config.spec_dir)
        errors = []
        
        if not spec_dir.exists():
            errors.append(f"Spec目录不存在: {self.config.spec_dir}")
        else:
            spec_files = list(spec_dir.glob("*.md"))
            if not spec_files:
                errors.append("未找到Spec文件")
            for sf in spec_files:
                content = sf.read_text(encoding="utf-8")
                # 基础校验：必须包含核心章节
                required_sections = ["## 一", "## 二", "## 三"]
                for sec in required_sections:
                    if sec not in content:
                        errors.append(f"{sf.name}: 缺少核心章节结构")
        
        status = PipelineStatus.PASSED if not errors else PipelineStatus.FAILED
        return StageResult("Stage1_SpecCheck", status, time.time()-start, "", errors)
    
    def _stage_code_generation(self) -> StageResult:
        """Stage 2: Spec→Code多Agent并行生成（原型模拟）"""
        start = time.time()
        output = []
        
        spec_dir = Path(self.config.spec_dir)
        output_dir = Path(self.config.output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        
        # 模拟：从Spec文件生成代码框架
        for sf in spec_dir.glob("*.md"):
            module_name = sf.stem.replace("-", "_").lower()
            code_file = output_dir / f"{module_name}.py"
            template = f'''"""
Auto-generated from spec: {sf.name}
Protocol: {module_name}
Generated by: Lobster CI Pipeline v1.0
"""
# TODO: 根据Spec实现完整业务逻辑
class {module_name.title().replace("_", "")}Engine:
    """实现自: {sf.name}"""
    pass
'''
            code_file.write_text(template, encoding="utf-8")
            output.append(f"Generated: {code_file}")
        
        return StageResult("Stage2_CodeGeneration", PipelineStatus.PASSED, 
                          time.time()-start, "\n".join(output))
    
    def _stage_test(self) -> StageResult:
        """Stage 3: 自动化测试"""
        start = time.time()
        errors = []
        coverage = 0.0
        output = ""
        
        test_dir = Path(self.config.test_dir)
        if test_dir.exists():
            try:
                # 运行pytest
                result = subprocess.run(
                    ["pytest", str(test_dir), "--cov", self.config.output_dir, 
                     "--cov-report=json", "-q"],
                    capture_output=True, text=True, timeout=120
                )
                output = result.stdout + result.stderr
                if result.returncode != 0:
                    errors.append(f"测试失败 (exit code: {result.returncode})")
                
                # 尝试读取覆盖率
                cov_file = Path("coverage.json")
                if cov_file.exists():
                    cov_data = json.loads(cov_file.read_text())
                    coverage = cov_data.get("totals", {}).get("percent_covered", 0)
            except FileNotFoundError:
                output = "pytest未安装或不可用（CI环境待配置）"
            except subprocess.TimeoutExpired:
                errors.append("测试执行超时（>120秒）")
        else:
            output = f"测试目录不存在: {self.config.test_dir}"
        
        status = PipelineStatus.PASSED if not errors else PipelineStatus.FAILED
        return StageResult("Stage3_Test", status, time.time()-start, output, errors, coverage)
    
    def _stage_quality_gate(self) -> StageResult:
        """Stage 4: 质量门禁"""
        start = time.time()
        errors = []
        
        # 覆盖率检查
        for r in self.results:
            if r.stage == "Stage3_Test" and r.coverage is not None:
                if r.coverage < self.config.coverage_threshold:
                    errors.append(f"代码覆盖率 {r.coverage:.1f}% < {self.config.coverage_threshold}% 阈值")
        
        # 复杂度检查（模拟ruff）
        try:
            result = subprocess.run(
                ["ruff", "check", self.config.output_dir, "--select=C90"],
                capture_output=True, text=True, timeout=30
            )
            if result.returncode != 0:
                errors.append(f"复杂度检查失败: {result.stderr[:200]}")
        except FileNotFoundError:
            pass  # ruff未安装则跳过
        
        status = PipelineStatus.PASSED if not errors else PipelineStatus.FAILED
        return StageResult("Stage4_QualityGate", status, time.time()-start, "", errors)
    
    def _stage_release(self) -> StageResult:
        """Stage 5: 版本发布"""
        start = time.time()
        output = []
        
        # 生成Changelog
        changelog = f"## Release {time.strftime('%Y%m%d-%H%M%S')}\n"
        changelog += f"- Pipeline: {self._summary()['status']}\n"
        for r in self.results:
            changelog += f"- {r.stage}: {r.status.value} ({r.duration:.1f}s)\n"
        
        changelog_path = Path(self.config.output_dir) / "CHANGELOG.md"
        changelog_path.write_text(changelog, encoding="utf-8")
        output.append(f"Changelog: {changelog_path}")
        
        return StageResult("Stage5_Release", PipelineStatus.PASSED, 
                          time.time()-start, "\n".join(output))
    
    def _summary(self) -> Dict:
        passed = sum(1 for r in self.results if r.status in (PipelineStatus.PASSED, PipelineStatus.FIXED))
        failed = sum(1 for r in self.results if r.status == PipelineStatus.FAILED)
        total_duration = time.time() - self.start_time
        
        return {
            "status": "PASSED" if failed == 0 else "FAILED",
            "stages_total": len(self.results),
            "stages_passed": passed,
            "stages_failed": failed,
            "total_duration": f"{total_duration:.1f}s",
            "coverage": next((r.coverage for r in self.results if r.coverage), None)
        }


