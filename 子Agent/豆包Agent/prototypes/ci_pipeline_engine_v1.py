class AutoFixEngine:
    """自动修复闭环：测试失败→分析→修复→重测"""
    
    def __init__(self, pipeline: CIPipeline, max_retries: int = 3):
        self.pipeline = pipeline
        self.max_retries = max_retries
        self.fix_history: List[Dict] = []
    
    def run_with_autofix(self) -> Dict:
        """带自动修复的流水线执行"""
        for attempt in range(1, self.max_retries + 1):
            summary = self.pipeline.run()
            
            if summary["status"] == "PASSED":
                return summary
            
            # 分析失败原因
            failed_stages = [r for r in self.pipeline.results if r.status == PipelineStatus.FAILED]
            for stage in failed_stages:
                fix_result = self._attempt_fix(stage, attempt)
                self.fix_history.append({
                    "attempt": attempt, "stage": stage.stage, 
                    "errors": stage.errors, "fix": fix_result
                })
                if fix_result["fixed"]:
                    stage.status = PipelineStatus.FIXED
            
            # 重新运行流水线
            self.pipeline.results = []
        
        return self.pipeline._summary()
    
    def _attempt_fix(self, stage: StageResult, attempt: int) -> Dict:
        """尝试自动修复"""
        fix_strategies = {
            "Stage1_SpecCheck": self._fix_spec_structure,
            "Stage3_Test": self._fix_test_coverage,
            "Stage4_QualityGate": self._fix_quality_issues
        }
        
        strategy = fix_strategies.get(stage.stage)
        if strategy:
            return strategy(stage, attempt)
        return {"fixed": False, "reason": "无可用的自动修复策略"}
    
    def _fix_spec_structure(self, stage: StageResult, attempt: int) -> Dict:
        """修复Spec结构：补充缺失章节"""
        # 读取错误信息，补充缺失结构
        return {"fixed": False, "reason": "Spec结构需手动补充，已记录缺失项"}
    
    def _fix_test_coverage(self, stage: StageResult, attempt: int) -> Dict:
        """修复测试覆盖率"""
        return {"fixed": False, "reason": f"测试覆盖率不足，需补充测试用例（第{attempt}次尝试）"}
    
    def _fix_quality_issues(self, stage: StageResult, attempt: int) -> Dict:
        """修复质量问题"""
        # 自动格式化 + Lint修复
        try:
            subprocess.run(["ruff", "check", "--fix", self.pipeline.config.output_dir], 
                          capture_output=True, timeout=30)
            return {"fixed": True, "action": "ruff自动修复"}
        except:
            return {"fixed": False, "reason": "ruff修复失败"}


